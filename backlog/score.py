"""Rank candidate use cases and write the prioritized backlog.

    python -m backlog.score            # writes docs/BACKLOG.md

Scores are weighted sums of workshop ratings. The point is not the decimal;
it is making the trade-offs explicit so a program executive can argue with a
specific rating instead of with the ranking as a whole.
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CRITERIA = ["mission_value", "volume", "feasibility", "data_readiness", "risk", "ato_path"]


def score(uc: dict, weights: dict) -> float:
    return round(sum(uc[c] * weights[c] for c in CRITERIA), 2)


def phase(uc: dict, s: float) -> str:
    if uc["risk"] <= 2 or uc["data_readiness"] <= 2:
        return "Phase 3: needs risk/data work first"
    if s >= 4.0:
        return "Phase 1: build now"
    if s >= 3.4:
        return "Phase 2: next quarter"
    return "Backlog: revisit or buy"


def render(data: dict) -> str:
    w = data["weights"]
    ranked = sorted(data["use_cases"], key=lambda u: -score(u, w))
    head = " | ".join(c.replace("_", " ") for c in CRITERIA)
    lines = [
        "# Prioritized use-case backlog",
        "",
        "Federal Grants Administration (fictional). Generated by `python -m backlog.score` from "
        "`backlog/use_cases.json`. Ratings are 1–5; for risk and ATO path, 5 means low risk / easy path.",
        "",
        "Weights: " + ", ".join(f"{c.replace('_', ' ')} {w[c]:.0%}" for c in CRITERIA),
        "",
        f"| Rank | Use case | Score | {head} | Max data level | Recommendation |",
        "|---|---|---|" + "---|" * len(CRITERIA) + "---|---|",
    ]
    for i, u in enumerate(ranked, 1):
        s = score(u, w)
        cells = " | ".join(str(u[c]) for c in CRITERIA)
        lines.append(f"| {i} | **{u['name']}** ({u['id']}) | {s:.2f} | {cells} | {u['max_data_level']} | {phase(u, s)} |")
    lines += ["", "## Details", ""]
    for u in ranked:
        lines += [f"### {u['id']} · {u['name']}",
                  f"- **Owner:** {u['owner']}",
                  f"- **Baseline:** {u['baseline']}",
                  f"- **Human decision point:** {u['human_decision']}",
                  f"- **Endpoint needed:** authorized for {u['max_data_level']}",
                  f"- **Notes:** {u['notes']}", ""]
    return "\n".join(lines)


def main() -> int:
    data = json.loads((ROOT / "backlog" / "use_cases.json").read_text())
    out = ROOT / "docs" / "BACKLOG.md"
    out.parent.mkdir(exist_ok=True)
    out.write_text(render(data))
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
